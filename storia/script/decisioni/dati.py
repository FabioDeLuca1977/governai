def nl(tipo, data, num):
    pref = {
        "L": "stato:legge",
        "DL": "stato:decreto.legge",
        "DLGS": "stato:decreto.legislativo",
        "LC": "stato:legge.costituzionale",
        "DPR": "presidente.repubblica:decreto",
    }[tipo]
    return f"Normattiva: https://www.normattiva.it/uri-res/N2Ls?urn:nir:{pref}:{data};{num}"

def cc(anno, num):
    return f"Corte costituzionale sent. {num}/{anno}: https://www.cortecostituzionale.it/actionSchedaPronuncia.do?anno={anno}&numero={num}"

